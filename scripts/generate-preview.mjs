#!/usr/bin/env node
// Generates a self-contained static preview of the landing from the real
// Next.js build output (spec 003 follow-up, 2026-10-30):
//   - reads .next/server/app/index.html (prerendered home of the active brand)
//   - inlines the compiled CSS, strips hydration scripts/preloads
//   - rewrites /projects/<slug>/... asset URLs to repo-relative paths
//   - writes projects/<slug>/preview.html
//
// Usage (after next build):
//   node scripts/generate-preview.mjs --slug=underundre
// Wired into package.json scripts build / build:underundre.

import fs from "node:fs";
import path from "node:path";

const repoRoot = path.resolve(new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1"));
const args = Object.fromEntries(
  process.argv.slice(2).map((a) => {
    const m = a.match(/^--([a-z-]+)=(.*)$/);
    return m ? [m[1], m[2]] : [];
  })
);
const slug = (args.slug || process.env.NEXT_PUBLIC_PROJECT_NAME || "underundre").toLowerCase();
// Spec 005 FR-016: reject traversal-looking slugs before they hit path.join.
if (!/^[a-z][a-z0-9-]*$/.test(slug)) {
  console.error(`✖ Invalid slug "${slug}" — must match ^[a-z][a-z0-9-]*$`);
  process.exit(1);
}

const prerendered = path.join(repoRoot, ".next", "server", "app", "index.html");
const outFile = path.join(repoRoot, "projects", slug, "preview.html");

if (!fs.existsSync(prerendered)) {
  console.error(`✖ ${prerendered} not found — run next build first.`);
  process.exit(1);
}

let html = fs.readFileSync(prerendered, "utf-8");

// Inline compiled CSS bundles (plus woff/woff2 fonts referenced from them as data URIs).
const fontCache = new Map();
function inlineFont(href) {
  if (fontCache.has(href)) return fontCache.get(href);
  const fontPath = path.join(repoRoot, ".next", ...href.slice("/_next/".length).split("/"));
  if (!fs.existsSync(fontPath)) return href;
  const dataUri = `data:font/woff2;base64,${fs.readFileSync(fontPath).toString("base64")}`;
  fontCache.set(href, dataUri);
  return dataUri;
}

html = html.replace(
  /<link rel="stylesheet" href="(\/_next\/[^"]+\.css)"[^>]*\/?>/g,
  (_, href) => {
    const cssPath = path.join(repoRoot, ".next", ...href.slice("/_next/".length).split("/"));
    if (!fs.existsSync(cssPath)) {
      console.warn(`⚠ CSS bundle not found for ${href} — leaving link as-is.`);
      return _;
    }
    const css = fs.readFileSync(cssPath, "utf-8").replace(/url\((\/_next\/[^)]+\.woff2?)\)/g, (_, fontHref) => `url(${inlineFont(fontHref)})`);
    return `<style>\n${css}\n</style>`;
  }
);

// Drop hydration scripts and preloads — the preview is a static visual snapshot.
html = html
  .replace(/<script\b[^>]*>[\s\S]*?<\/script>/g, "")
  .replace(/<script\b[^>]*\/>/g, "")
  .replace(/<link[^>]+rel="(preload|modulepreload)"[^>]+as="script"[^>]*>/g, "");

// Rewrite absolute project-asset URLs to paths that resolve when the file
// is opened from disk (preview.html lives at projects/<slug>/preview.html).
html = html.replaceAll(`src="/projects/${slug}/`, 'src="../../public/projects/' + slug + "/");
html = html.replaceAll(`href="/projects/${slug}/`, 'href="../../public/projects/' + slug + "/");

// Mark as generated.
html = html.replace(
  "<head>",
  `<head>\n  <!-- GENERATED by scripts/generate-preview.mjs — do not edit by hand. Regenerate: pnpm build:${slug === "underundre" ? "underundre" : "build"} -->`
);

fs.writeFileSync(outFile, html);
console.log(
  `✔ Preview written: projects/${slug}/preview.html (${(html.length / 1024).toFixed(1)} kB, scripts stripped, CSS inlined)`
);
